async function seedIndianAccounts() {
  console.log('🔗 Connecting to MongoDB Atlas...');
  const client = new MongoClient(plutoUri);

  try {
    await client.connect();
    console.log('✅ Connected to MongoDB Atlas');

    const db = client.db('pluto');
    const col = db.collection('email_accounts');

    // 1. Delete old test data
    console.log('🧹 Removing old test email accounts...');
    const delResult = await col.deleteMany({});
    console.log(`✅ Removed ${delResult.deletedCount} old test records.`);

    // 2. Insert the 20 realistic Indian accounts
    console.log('🚀 Inserting 20 authentic Indian outreach email accounts...');
    const formattedDocs = indianAccounts.map(acc => ({
      _id: new ObjectId(),
      id: Long.fromNumber(acc.id),
      user_id: acc.user_id,
      email: acc.email,
      first_name: acc.first_name,
      last_name: acc.last_name,
      extension: acc.extension,
      phone_number: acc.phone_number,
      designation: acc.designation,
      postal_code: acc.postal_code,
      address: acc.address,
      fax: acc.fax,
      unsubscribe: acc.unsubscribe,
      daily_send_limit: acc.daily_send_limit,
      used_quota: acc.used_quota,
      region: acc.region,
      status: acc.status,
      type: acc.type,
      created_at: acc.created_at,
      updated_at: acc.updated_at
    }));

    const insertResult = await col.insertMany(formattedDocs);
    console.log(`🎉 Successfully inserted ${insertResult.insertedCount} Indian email accounts!`);

    // Verify
    const count = await col.countDocuments({});
    console.log(`📊 Total email accounts now in Pluto: ${count}`);

  } catch (error) {
    console.error('❌ Seeding failed:', error);
  } finally {
    await client.close();
    console.log('🔌 Connection closed.');
  }
}

seedIndianAccounts();
